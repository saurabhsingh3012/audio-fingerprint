"""REAL Creative-Commons music corpus: download, decode, attribute.

This module is the bridge from the SYNTHETIC evaluation (:mod:`audio_fingerprint.synth`)
to **real recorded music**. It fetches a modest set of Creative-Commons-licensed
tracks from the Internet Archive ``netlabels`` collection, decodes them to mono
arrays at the pipeline's working sample rate, and records provenance and license
for every track so the corpus is fully attributable and reproducible.

Why the Internet Archive ``netlabels`` collection
-------------------------------------------------
It is large (tens of thousands of items), reliably reachable over plain HTTP, and
every item selected here carries an explicit ``creativecommons.org`` license URL —
the search query filters on ``licenseurl`` so nothing without a CC license is ever
downloaded. The audio is *real released music* (electronic, experimental, jazz,
hip-hop, ...), which is exactly the point: unlike the synthetic corpus, it has
vibrato, inharmonicity, real production chains, and — because tracks come from the
same netlabels and albums — genuinely confusable material, which is what stresses
the false-accept side of the evaluation.

What is and is not redistributed
--------------------------------
**No audio is committed to the repository.** Downloads are cached under ``data/``
(git-ignored). What the project commits is code, the measured results JSON, and
``DATA_SOURCES.md`` — a plain-text attribution table (title, creator, license,
Archive.org identifier) generated by :func:`write_data_sources`. Fingerprints and
indices are derived statistics, not the audio, and are also kept out of git. This
respects even the NonCommercial / NoDerivatives CC variants: the audio is used
locally for analysis and is attributed, never re-hosted.

Dependency isolation
--------------------
The network and heavy-audio dependencies (:mod:`librosa`, :mod:`soundfile`) are
imported **lazily inside functions**. Importing the core ``audio_fingerprint``
package therefore stays numpy/scipy-only, and the synthetic evaluation and CI
never touch the network or require the extra packages. Install them with the
optional extra: ``pip install -e ".[real]"``.
"""

