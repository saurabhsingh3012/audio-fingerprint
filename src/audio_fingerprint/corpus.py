def build_manifest(
    *,
    n_reference: int,
    n_impostors: int,
    data_dir: str | Path,
    query: str = DEFAULT_QUERY,
    min_seconds: float = 40.0,
    max_seconds: float = 300.0,
    target_seconds: float = 120.0,
    max_bytes: int = 7_000_000,
    rate_limit_s: float = 1.1,
    verbose: bool = True,
) -> dict:
    """Download a REAL corpus and write ``manifest.json`` under ``data_dir``.

    Scans the search results in a deterministic order, takes **one** track per
    item (for artist/album diversity), downloads it, verifies it decodes to
    non-silent audio, and assigns roles: the first ``n_reference`` good tracks are
    indexed, the next ``n_impostors`` are held out to measure false accepts.

    Returns the manifest dict (also written to disk). Idempotent at the file
    level: an already-downloaded audio file is not re-fetched.
    """
    data_dir = Path(data_dir)
    audio_dir = data_dir / "audio"
    audio_dir.mkdir(parents=True, exist_ok=True)
    n_total = n_reference + n_impostors

    records: list[TrackRecord] = []
    seen_items: set[str] = set()
    for ident in _iter_identifiers(query, rate_limit_s=rate_limit_s):
        if len(records) >= n_total:
            break
        if ident in seen_items:
            continue
        seen_items.add(ident)
        try:
            meta = _get_json(_METADATA.format(identifier=ident), rate_limit_s=rate_limit_s)
        except RuntimeError:
            continue
        md = meta.get("metadata", {})
        license_url = md.get("licenseurl", "")
        if "creativecommons" not in license_url:
            continue  # defensive: the query already filters, but never trust it
        chosen = _pick_file(
            meta, min_s=min_seconds, max_s=max_seconds,
            max_bytes=max_bytes, target_s=target_seconds,
        )
        if chosen is None:
            continue

        track_id = len(records)
        safe = f"{ident}__{chosen['name']}".replace("/", "_")
        dest = audio_dir / safe
        if not dest.exists():
            url = _DOWNLOAD.format(
                identifier=ident, filename=urllib.parse.quote(chosen["name"])
            )
            try:
                dest.write_bytes(_http_get(url, rate_limit_s=rate_limit_s, timeout=120.0))
            except RuntimeError:
                continue
        try:
            decode_track(dest)  # validate; discard undecodable/silent files
        except Exception:  # noqa: BLE001 - a bad decode just means skip this track
            dest.unlink(missing_ok=True)
            continue

        creator = md.get("creator", "")
        if isinstance(creator, list):
            creator = creator[0] if creator else ""
        title = md.get("title", ident)
        name = f"{creator} — {title}".strip(" —") or ident
        role = "reference" if track_id < n_reference else "impostor"
        rec = TrackRecord(
            track_id=track_id, name=name[:120], role=role, identifier=ident,
            filename=chosen["name"], title=str(title)[:120], creator=str(creator)[:80],
            license=license_url, length_s=round(float(chosen["length"]), 2),
            bytes=int(chosen["size"]), rel_path=str(dest.relative_to(data_dir)),
        )
        records.append(rec)
        if verbose:
            lic_short = rec.license.split("/licenses/")[-1]
            print(f"  [{track_id:2d}/{n_total}] {role:9s} {lic_short:14s} "
                  f"{rec.length_s:6.1f}s  {rec.name[:52]}")

    if len(records) < n_total:
        print(f"WARNING: only {len(records)}/{n_total} tracks obtained "
              f"(reference target {n_reference}, impostor target {n_impostors})")

    manifest = dict(
        query=query, sample_rate=SAMPLE_RATE, n_reference=n_reference,
        n_impostors=n_impostors, n_obtained=len(records),
        created_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        tracks=[asdict(r) for r in records],
    )
    (data_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return manifest


def load_manifest(data_dir: str | Path) -> dict | None:
    """Load ``manifest.json`` from ``data_dir``, or ``None`` if absent."""
    path = Path(data_dir) / "manifest.json"
    if not path.exists():
        return None
    return json.loads(path.read_text())


def load_corpus(manifest: dict, data_dir: str | Path) -> RealCorpus:
    """Decode every track in ``manifest`` into a :class:`RealCorpus`."""
    data_dir = Path(data_dir)
    sr = int(manifest.get("sample_rate", SAMPLE_RATE))
    specs = [TrackRecord(**t) for t in manifest["tracks"]]
    audio: dict[int, NDArray[np.float64]] = {}
    for rec in specs:
        audio[rec.track_id] = decode_track(data_dir / rec.rel_path, sample_rate=sr)
    return RealCorpus(specs=specs, audio=audio, sample_rate=sr)


def ensure_corpus(
    *,
    n_reference: int,
    n_impostors: int,
    data_dir: str | Path,
    allow_download: bool = True,
    **build_kwargs: object,
) -> RealCorpus:
    """Return a decoded :class:`RealCorpus`, building/downloading it if needed.

    If a manifest already covers at least ``n_reference + n_impostors`` tracks and
    every cached file is present, it is loaded without any network access. This is
    what lets the evaluation be re-run offline once the corpus is cached.
    """
    data_dir = Path(data_dir)
    manifest = load_manifest(data_dir)
    need = n_reference + n_impostors
    have = manifest["n_obtained"] if manifest else 0
    files_ok = bool(manifest) and all(
        (data_dir / t["rel_path"]).exists() for t in manifest["tracks"]
    )
    if manifest and have >= need and files_ok:
        return load_corpus(manifest, data_dir)
    if not allow_download:
        raise RuntimeError(
            f"no cached corpus for {need} tracks under {data_dir} and downloads "
            f"are disabled (allow_download=False)"
        )
    manifest = build_manifest(
        n_reference=n_reference, n_impostors=n_impostors, data_dir=data_dir,
        **build_kwargs,  # type: ignore[arg-type]
    )
    return load_corpus(manifest, data_dir)


def write_data_sources(manifest: dict, path: str | Path) -> None:
    """Write a committed, audio-free attribution table for the corpus.

    Lists every track with its title, creator, exact CC license, and Archive.org
    identifier so the corpus is fully attributable from the repository without any
    audio being redistributed.
    """
    tracks = manifest["tracks"]
    lines = [
        "# Data sources — REAL audio corpus",
        "",
        "Every track below is a Creative-Commons-licensed recording from the "
        "Internet Archive [`netlabels`](https://archive.org/details/netlabels) "
        "collection, fetched by "
        "[`src/audio_fingerprint/corpus.py`](src/audio_fingerprint/corpus.py).",
        "",
        "**No audio is redistributed in this repository.** Files are cached locally "
        "under `data/` (git-ignored) and used only for fingerprinting and "
        "evaluation. This table is the attribution required by the CC licenses; "
        "each row links to the original item, which carries the authoritative "
        "license and full credits.",
        "",
        f"- Search query: `{manifest['query']}`",
        f"- Tracks: {manifest['n_obtained']} "
        f"({manifest['n_reference']} reference / indexed, "
        f"{manifest['n_impostors']} impostor / held out)",
        f"- Working sample rate: {manifest['sample_rate']} Hz (mono)",
        f"- Manifest created: {manifest['created_utc']}",
        "",
        "| # | role | title | creator | license | archive.org item | length |",
        "|--:|------|-------|---------|---------|------------------|-------:|",
    ]
    for t in tracks:
        lic = t["license"]
        lic_short = lic.split("/licenses/")[-1].rstrip("/") if "/licenses/" in lic else lic
        url = f"https://archive.org/details/{t['identifier']}"
        title = str(t["title"]).replace("|", "\\|")
        creator = str(t["creator"]).replace("|", "\\|") or "—"
        lines.append(
            f"| {t['track_id']} | {t['role']} | {title} | {creator} | "
            f"[{lic_short}]({lic}) | [`{t['identifier']}`]({url}) | {t['length_s']:.0f}s |"
        )
    lines.append("")
    Path(path).write_text("\n".join(lines))


def _main(argv: list[str] | None = None) -> None:
    """CLI: download the corpus and (re)generate ``DATA_SOURCES.md``."""
    import argparse

    parser = argparse.ArgumentParser(description="Download a REAL CC-licensed music corpus.")
    parser.add_argument("--n-reference", type=int, default=36)
    parser.add_argument("--n-impostors", type=int, default=12)
    parser.add_argument("--data-dir", type=str, default=str(
        Path(__file__).resolve().parents[2] / "data"))
    parser.add_argument("--data-sources-out", type=str, default=str(
        Path(__file__).resolve().parents[2] / "DATA_SOURCES.md"))
    parser.add_argument("--min-seconds", type=float, default=40.0)
    parser.add_argument("--max-seconds", type=float, default=300.0)
    parser.add_argument("--target-seconds", type=float, default=120.0)
    parser.add_argument("--max-bytes", type=int, default=7_000_000)
    parser.add_argument("--rate-limit", type=float, default=1.1)
    args = parser.parse_args(argv)

    print(f"downloading {args.n_reference} reference + {args.n_impostors} impostor "
          f"tracks into {args.data_dir} ...")
    manifest = build_manifest(
        n_reference=args.n_reference, n_impostors=args.n_impostors, data_dir=args.data_dir,
        min_seconds=args.min_seconds, max_seconds=args.max_seconds,
        target_seconds=args.target_seconds, max_bytes=args.max_bytes,
        rate_limit_s=args.rate_limit,
    )
    write_data_sources(manifest, args.data_sources_out)
    print(f"wrote manifest ({manifest['n_obtained']} tracks) and {args.data_sources_out}")


if __name__ == "__main__":
    _main()
