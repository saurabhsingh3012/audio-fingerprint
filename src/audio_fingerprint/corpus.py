def decode_track(
    path: str | Path, *, sample_rate: int = SAMPLE_RATE, normalize_rms: float = 0.1
) -> NDArray[np.float64]:
    """Decode an audio file to a mono float64 array at ``sample_rate``.

    Args:
        path: Audio file on disk.
        sample_rate: Target rate; librosa resamples to it.
        normalize_rms: If > 0, scale the whole track to this RMS. The fingerprint
            is gain-invariant so this does not change matching, but it keeps every
            track at a comparable loudness (matching the synthetic corpus's
            convention) and gives the measured-SNR degradation a stable reference.

    Returns:
        A mono signal. Raises if the file cannot be decoded to non-silent audio.
    """
    import librosa  # lazy: keeps the core package import network/audio-free

    audio, _ = librosa.load(str(path), sr=sample_rate, mono=True)
    audio = np.asarray(audio, dtype=np.float64)
    rms = float(np.sqrt(np.mean(audio**2))) if audio.size else 0.0
    if audio.size == 0 or rms <= 1e-8:
        raise ValueError(f"decoded audio is empty or silent: {path}")
    if normalize_rms > 0:
        audio = audio * (normalize_rms / rms)
    return audio


