# Selection
# --------------------------------------------------------------------------


def _iter_identifiers(
    query: str, *, rate_limit_s: float, page_size: int = 100, max_pages: int = 40
) -> Iterator[str]:
    """Yield item identifiers for ``query``, paged and stably sorted.

    Sorting by ``identifier`` makes the scan order deterministic, so the same
    filters select the same tracks on every run (network permitting) — which is
    what lets the manifest be a faithful, reproducible description of the corpus.
    """
    for page in range(1, max_pages + 1):
        params = {
            "q": query,
            "fl[]": "identifier",
            "rows": str(page_size),
            "page": str(page),
            "sort[]": "identifier asc",
            "output": "json",
        }
        url = _ADVSEARCH + "?" + urllib.parse.urlencode(params, doseq=True)
        docs = _get_json(url, rate_limit_s=rate_limit_s)["response"]["docs"]
        if not docs:
            return
        for doc in docs:
            ident = doc.get("identifier")
            if ident:
                yield ident


def _pick_file(
    meta: dict, *, min_s: float, max_s: float, max_bytes: int, target_s: float
) -> dict | None:
    """Choose one suitable MP3 from an item, deterministically.

    Keeps files whose duration is in ``[min_s, max_s]`` and whose size is at most
    ``max_bytes``, then picks the one closest to ``target_s`` (ties broken by
    name). Preferring a mid-length track avoids album intros/interludes and keeps
    per-file size bounded so the whole corpus stays a modest download.
    """
    suitable: list[dict] = []
    for f in meta.get("files", []):
        if f.get("format") != "VBR MP3":
            continue
        if not f.get("name", "").lower().endswith(".mp3"):
            continue
        try:
            length = float(f.get("length", 0.0))
            size = int(f.get("size", 0))
        except (TypeError, ValueError):
            continue
        if min_s <= length <= max_s and 0 < size <= max_bytes:
            suitable.append({"name": f["name"], "length": length, "size": size})
    if not suitable:
        return None
    suitable.sort(key=lambda f: (abs(f["length"] - target_s), f["name"]))
    return suitable[0]


