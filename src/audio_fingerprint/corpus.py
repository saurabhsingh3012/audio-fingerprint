#: Search that returns only CC-licensed music audio with a variable-bitrate MP3.
#: ``licenseurl:(*creativecommons*)`` guarantees every hit is attributable.
DEFAULT_QUERY = (
    "collection:netlabels AND mediatype:audio "
    "AND format:(VBR MP3) AND licenseurl:(*creativecommons*)"
)

_ADVSEARCH = "https://archive.org/advancedsearch.php"
_METADATA = "https://archive.org/metadata/{identifier}"
_DOWNLOAD = "https://archive.org/download/{identifier}/{filename}"

_USER_AGENT = "audio-fingerprint-research/0.1 (github.com/saurabhsingh3012/audio-fingerprint)"

#: Working sample rate; matched to the fingerprint pipeline so no config juggling
#: is needed downstream. librosa resamples on decode.
SAMPLE_RATE = DEFAULT_CONFIG.sample_rate

_last_request_at = 0.0


def _polite_sleep(min_interval_s: float) -> None:
    """Sleep so consecutive network calls are at least ``min_interval_s`` apart.

    The Internet Archive asks automated clients to rate-limit; this keeps the
    whole download well under one request per second on average.
    """
    global _last_request_at
    now = time.monotonic()
    wait = min_interval_s - (now - _last_request_at)
    if wait > 0:
        time.sleep(wait)
    _last_request_at = time.monotonic()


def _http_get(url: str, *, rate_limit_s: float, retries: int = 3, timeout: float = 45.0) -> bytes:
    """GET ``url`` with a user agent, rate limiting, and bounded retries."""
    last_err: Exception | None = None
    for attempt in range(retries):
        _polite_sleep(rate_limit_s)
        try:
            req = urllib.request.Request(url, headers={"User-Agent": _USER_AGENT})
            with urllib.request.urlopen(req, timeout=timeout) as resp:  # noqa: S310 - https only
                return resp.read()
        except Exception as err:  # noqa: BLE001 - network is flaky; retry then give up
            last_err = err
            time.sleep(1.0 + attempt)
    raise RuntimeError(f"GET failed after {retries} attempts: {url}\n  last error: {last_err}")


def _get_json(url: str, *, rate_limit_s: float) -> dict:
    """GET and parse a JSON document."""
    return json.loads(_http_get(url, rate_limit_s=rate_limit_s).decode("utf-8"))


@dataclass(frozen=True)
class TrackRecord:
    """Provenance and location of one REAL track.

    Attributes:
        track_id: Stable identifier used by the index and evaluation.
        name: Display name (``"creator — title"``), also what the index stores.
        role: ``"reference"`` (indexed) or ``"impostor"`` (held out of the index,
            used only to measure the false-accept rate).
        identifier: Internet Archive item identifier.
        filename: MP3 file name within the item.
        title: Track title from the item metadata.
        creator: Artist / creator string.
        license: Full Creative-Commons license URL. Never empty by construction.
        length_s: Track duration in seconds, as reported by Archive.org.
        bytes: File size on disk.
        rel_path: Path to the cached audio, relative to the data directory.
    """

    track_id: int
    name: str
    role: str
    identifier: str
    filename: str
    title: str
    creator: str
    license: str
    length_s: float
    bytes: int
    rel_path: str


@dataclass
class RealCorpus:
    """A decoded REAL corpus, duck-compatible with :class:`synth.Corpus`.

    Exposes ``specs`` (each with ``track_id`` and ``name``) and an ``audio`` dict
    keyed by ``track_id``, so the existing evaluation helpers accept it unchanged.
    """

    specs: list[TrackRecord]
    audio: dict[int, NDArray[np.float64]] = field(default_factory=dict)
    sample_rate: int = SAMPLE_RATE

    def __len__(self) -> int:
        return len(self.specs)

    def with_role(self, role: str) -> RealCorpus:
        """A view containing only tracks with the given ``role``."""
        specs = [s for s in self.specs if s.role == role]
        return RealCorpus(
            specs=specs,
            audio={s.track_id: self.audio[s.track_id] for s in specs if s.track_id in self.audio},
            sample_rate=self.sample_rate,
        )


